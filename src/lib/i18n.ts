export function tr(lang: Lang, key: MsgKey, vars?: Record<string, string | number>) {
  let s = TABLES[lang]?.[key] ?? th[key] ?? key;
  if (vars) {
    for (const [k, v] of Object.entries(vars)) s = s.replaceAll(`{${k}}`, String(v));
  }
  return s;
}

